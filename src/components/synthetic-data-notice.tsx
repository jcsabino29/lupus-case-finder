import { ShieldCheck } from "lucide-react";
import { cn } from "@/lib/utils";

/**
 * Persistent notice that the app only ever holds synthetic data.
 * Rendered as a landmark note so screen readers announce it.
 */
export function SyntheticDataNotice({ className }: { className?: string }) {
  return (
    <aside
      aria-label="Data notice"
      className={cn(
        "flex items-start gap-3 rounded-lg border border-warning/30 bg-warning-soft p-4 text-sm",
        className,
      )}
    >
      <ShieldCheck aria-hidden="true" className="mt-0.5 size-5 shrink-0 text-warning" />
      <div className="space-y-1">
        <p className="font-medium text-fg">Synthetic data only. No real patient data.</p>
        <p className="text-fg-muted">
          Every patient in this demo is generated by Synthea and is not a real person. Never upload,
          paste or connect real medical records (PHI) to this app.
        </p>
      </div>
    </aside>
  );
}
